const SAME = { А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X', І: 'I', "'": '’' };
const glyph = ch => G[ch] ?? G[SAME[ch]] ?? G['·'];

/** Рядок → масив стовпців (кожен — 7 бітів), з порожнім стовпцем між знаками */
export function columns(text) {
  const out = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const rows = glyph(ch).split('|'), w = rows[0].length;
    if (i) out.push(0);
    for (let x = 0; x < w; x++) { let col = 0; for (let y = 0; y < 7; y++) if (rows[y][x] === '#') col |= 1 << y; out.push(col); }
  });
  return out;
}
