// Одиниця довжини U — один піксель спрайта КІ-Рекса; рівень складено з клітинок 8×8 U.
// Фізика рахується «за шляхом», а не за часом: стрибок задано формою (висота й довжина), тож на будь-якій
// швидкості бігу КІ-Рекс проходить ту саму дугу, і намальовані вручну шаблони лишаються прохідними.
