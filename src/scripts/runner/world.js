/* Два набори правил: повний (клавіатура) і легший для гри дотиком — повільніший, з довшими перепочинками.
   speed0 — швидкість на старті, U/с;
   grow — у стільки разів біг прискорюється за кожен відрізок карти (як складні відсотки): з клавіатури це +2,5 %
          за пору року, від 54 до 88,5 U/с на фініші; дотиком +1,9 %, від 48 до 70 U/с. Швидше дотиком не можна:
          на найвужчому телефоні видно 84 U траси перед КІ-Рексом, а гравець має бачити її щонайменше на 1,2 с уперед;
   rest — перепочинок між шаблонами (клітинок) у кожен із чотирьох років */
const RULES = {
  full: { speed0: 54, grow: 1.025, rest: [9, 8, 7, 7], intro: INTRO, levels: LEVELS },
  touch: { speed0: 48, grow: 1.019, rest: [11, 10, 9, 9], intro: TOUCH_INTRO, levels: TOUCH_LEVELS },
};
const COUNT = [4, 6, 8, 10];                       // скільки шаблонів у відрізку кожного з чотирьох років

/* Маленький генератор «випадкових» чисел із зерном: те саме зерно — та сама послідовність. Тому карта щоразу однакова */
function seeded(a) {
  return () => {
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hasBug = p => p.some(row => /m/i.test(row));
/* Шаблони n-го відрізка карти (n = 0…19); s — яка це пора року; touch — гра дотиком.
   Перший відрізок — розгін. Перший рік — чотири найпростіші шаблони своєї пори, другий — усі шість, у написаному порядку.
   Третій і четвертий — шість і ще кілька повторів, «перемішані» генератором із зерном, що залежить лише від номера відрізка:
   порядок щоразу той самий. Жуки при цьому ніколи не стоять поруч */
export function segment(n, s, touch = false) {
  const r = RULES[touch ? 'touch' : 'full'];
  const all = r.levels[s];
  const want = COUNT[Math.floor(n / PER_YEAR)];
  if (n === 0) return r.intro.slice();
  let list = all.slice(0, want);
  if (want <= all.length) return list;
  const rnd = seeded(n * 2 + (touch ? 1 : 0));
  const plain = all.filter(p => !hasBug(p));
  while (list.length < want) list.push(plain[Math.floor(rnd() * plain.length)]);
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  // жуків розставляємо по одному в різні проміжки між іншими шаблонами
  const bugs = list.filter(hasBug);
  const gaps = [];
  list = list.filter(p => !hasBug(p));
  for (let g = 1; g <= list.length; g++) gaps.push(g);
  bugs
    .map(b => [gaps.splice(Math.floor(rnd() * gaps.length), 1)[0], b])
    .sort((a, b) => b[0] - a[0])
    .forEach(([g, b]) => list.splice(g, 0, b));
  return list;
}

/* Швидкість росте плавно, без стрибків на межі пір року: на початку n-го відрізка вона speed0 · grow^n,
   а всередині відрізка n — дробове число (номер відрізка плюс пройдена його частка), тож до кінця відрізка
   вона доростає рівно до стартової швидкості наступного. Що далі, то крутіше: кожна пора року додає той самий відсоток */
export const startSpeed = (n, touch = false) => {
  const r = RULES[touch ? 'touch' : 'full'];
  return r.speed0 * r.grow ** n;
};
function speedOf(w) {
  const m = w.marks[w.mi];
  const done = Math.min(1, Math.max(0, (w.dist - m.x) / (m.end - m.x)));
  return startSpeed(m.n + done, w.touch);
}
/* яка пора року на трасі в точці x (за нею view.js вибирає вигляд землі, дерев, перешкод і погоди) */
export const seasonAt = (w, x) => {
  let s = w.marks[0].s;
  for (const m of w.marks) {
    if (x >= m.x) s = m.s;
  }
  return s;
};
export const score = w => Math.floor(w.dist / CELL) + w.bonus;
/* з якої пори року починати — за календарем: грудень–лютий зима (0), березень–квітень весна (1), травень сакура (2),
   червень–серпень літо (3), вересень–листопад осінь (4) */
export const seasonNow = (d = new Date()) => [0, 0, 1, 1, 2, 3, 3, 3, 4, 4, 4, 0][d.getMonth()];

/* Новий світ. season — з якої пори року почати. Параметри:
     ahead — скільки траси тримати попереду (ширина екрана з запасом);
     touch — гра дотиком (лише стрибок, легший набір шаблонів);
     from  — контрольна точка попереднього забігу (w.check): гра продовжується з початку того самого відрізка —
             з тими самими перешкодами, тим самим рахунком і в тому самому режимі */
export function createWorld(season = 0, { ahead = 320, touch = false, from = null } = {}) {
  if (from) touch = from.touch;
  // контрольна точка — початок відрізка: s — яка пора, n — котрий відрізок карти, x — відстань, score — рахунок,
  // speed — швидкість на ту мить
  const check = from || { s: season, n: 0, x: 0, score: 0, speed: startSpeed(0, touch), touch };
  const w = {
    touch,
    check,
    dist: check.x,
    speed: check.speed,
    // bonus — очки понад пройдений шлях (біти)
    bonus: check.score - Math.floor(check.x / CELL),
    ev: 0,
    dead: false,
    won: false,
    hit: null,
    // behind — скільки траси тримати позаду (теж задає runner.js)
    ahead,
    behind: 48,
    // h — висота ніг над землею, vy — нахил дуги
    pl: { h: 0, vy: 0, floor: 0, ground: true, duck: false, lock: false, coyote: 0, buffer: 0 },
    // перешкоди на трасі й запас використаних об'єктів
    obs: [],
    pool: [],
    // відрізки на трасі: від x до end; mi — у котрому зараз гравець
    marks: [{ x: check.x, end: 0, s: check.s, n: check.n }],
    mi: 0,
    queue: [],
    rest: 0,
    nextX: check.x + LEAD,
    // finish — де закінчується карта (стає відомо, коли добудовано останній відрізок)
    finish: Infinity,
  };
  plan(w, w.marks[0]);
  spawn(w);
  return w;
}

/* черга шаблонів відрізка й місце, де він закінчиться: посеред перепочинку після останнього шаблону */
function plan(w, m) {
  w.queue = segment(m.n, m.s, w.touch);
  w.rest = RULES[w.touch ? 'touch' : 'full'].rest[Math.floor(m.n / PER_YEAR)];
  m.end = w.nextX + w.queue.reduce((sum, p) => sum + (p[0].length + w.rest) * CELL, 0) - w.rest * CELL / 2;
}
/* добудовує трасу попереду гравця; коли шаблони відрізка скінчилися — починається наступний, а після останнього — фініш */
function spawn(w) {
  while (w.nextX < w.dist + w.ahead && w.finish === Infinity) {
    if (!w.queue.length) {
      const last = w.marks[w.marks.length - 1];
      if (last.n === SEGMENTS - 1) {
        w.finish = last.end;
        return;
      }
      const m = { x: last.end, end: 0, s: (last.s + 1) % PER_YEAR, n: last.n + 1 };
      w.marks.push(m);
      plan(w, m);
    }
    const p = w.queue.shift();
    place(w, p, w.nextX, w.marks[w.marks.length - 1].s);
    w.nextX += (p[0].length + w.rest) * CELL;
  }
}
/* шаблон → перешкоди. cx, cy — лівий нижній кут клітинки (для малювання); x, y, w, h — зона зіткнення; s — пора року (вигляд) */
export function place(w, rows, x0, s = w.marks[w.mi].s) {
  const H = rows.length;
  const add = (kind, cx, cy, x, y, bw, bh) => {
    const o = w.pool.pop() || {};
    o.kind = kind;
    o.s = s;
    o.cx = cx;
    o.cy = cy;
    o.x = x;
    o.y = y;
    o.w = bw;
    o.h = bh;
    o.used = false;
    w.obs.push(o);
    return o;
  };
  for (let c = 0; c < rows[0].length; c++) {
    for (let r = 0; r < H; r++) {
      const ch = rows[H - 1 - r][c];
      const cx = x0 + c * CELL;
      const cy = r * CELL;
      if (ch === '^') add('spike', cx, cy, cx + 2, cy, 4, 6);
      else if (ch === '#') add('block', cx, cy, cx, cy, CELL, CELL);
      else if (ch === 'v') add('gate', cx, cy, cx + 1, cy - 3, 6, 999);
      else if (ch === 'm' || ch === 'M') {
        // зона — середина тільця: без крил і лапок
        const by = ch === 'm' ? BUG.low : BUG.high;
        add('bug', cx, by, cx + 1, by + 1.5, 6, 3);
      }
      else if (ch === 'j') add('pad', cx, cy, cx + 1, cy, 6, 4);
      else if (ch === 'o') add('orb', cx, cy, cx - 3, cy - 3, 14, 14);
    }
  }
}

/* Поштовх угору (стрибок, пружина, біт). vy — бажаний нахил дуги; що ближче КІ-Рекс до стелі TOP, то слабший поштовх:
   дуга сама згинається нижче стелі, тож він ніколи не вилітає за верх поля й не б'ється об невидиму стіну */
function launch(w, vy, ev) {
  const p = w.pl;
  p.vy = Math.min(vy, Math.sqrt(2 * G * Math.max(0, TOP - p.h)));
  p.ground = false;
  p.coyote = 0;
  p.buffer = 0;
  w.ev |= ev;
}

/* Один крок світу на dt секунд. inp — ввід: press (щойно натиснуто «стрибок»; крок сам скидає),
   hold (кнопку «стрибок» тримають), down (тримають «униз»; у грі дотиком не діє) */
export function step(w, inp, dt) {
  const p = w.pl;
  const down = inp.down && !w.touch;
  w.ev = 0;
  w.speed = speedOf(w);
  const dx = w.speed * dt;
  w.dist += dx;

  // «вниз» на землі — пригнутися, у повітрі — різко до землі. Якщо ж «вниз» затиснуто ще з землі (КІ-Рекс пригинався
  // й одразу стрибнув), він стрибку не заважає: lock тримається, доки клавішу не відпустять
  if (p.ground || !down) p.lock = p.ground && down;

  // стрибок: буфер пам'ятає натискання, зроблене трохи зарано, «час койота» дозволяє стрибнути, щойно зійшовши з краю;
  // якщо кнопку тримають — КІ-Рекс стрибає знову, щойно торкнеться землі
  if (inp.press) {
    p.buffer = BUFFER;
    inp.press = false;
  } else p.buffer = Math.max(0, p.buffer - dt);
  p.coyote = p.ground ? COYOTE : Math.max(0, p.coyote - dt);
  if (p.coyote > 0 && (p.buffer > 0 || (inp.hold && !down))) launch(w, V_JUMP, EV.JUMP);

  // політ дугою: висота змінюється за пройдений шлях dx; «вниз», натиснутий уже в повітрі, — різко до землі
  const from = p.h;
  if (!p.ground) {
    let g = G;
    if (down && !p.lock) {
      p.vy = Math.min(p.vy, V_SLAM);
      g *= 3;
    }
    p.h += p.vy * dx - g * dx * dx / 2;
    p.vy = Math.max(V_MAX, p.vy - g * dx);
  }

  // опора під ногами: земля або верх блока, на який КІ-Рекс опускається згори (чи зачепив кут не нижче STEP_UP)
  const x0 = w.dist;
  let floor = 0;
  for (const o of w.obs) {
    if (o.kind === 'block' && o.x < x0 + STAND.w && o.x + o.w > x0 && o.y + o.h <= from + STEP_UP) {
      floor = Math.max(floor, o.y + o.h);
    }
  }
  p.floor = floor;
  if (p.h <= floor) {
    if (!p.ground) w.ev |= EV.LAND;
    p.h = floor;
    p.vy = 0;
    p.ground = true;
  } else {
    // зійшов із краю блока — далі падає
    p.ground = false;
  }

  // зіткнення: зона КІ-Рекса проти зони кожної перешкоди. Пружина й біт не шкодять ніколи: вони лише підкидають
  p.duck = down && p.ground;
  const box = p.duck ? DUCK : STAND;
  const x1 = x0 + box.w;
  const y0 = p.h;
  const y1 = y0 + box.h;
  for (const o of w.obs) {
    // пройшов під навісною
    if (o.kind === 'gate' && !o.used && o.x + o.w <= x0) {
      o.used = true;
      w.ev |= EV.GATE;
    }
    if (o.x >= x1 || o.x + o.w <= x0 || o.y >= y1 || o.y + o.h <= y0) continue;
    if (o.kind === 'pad') {
      if (!o.used) {
        o.used = true;
        launch(w, V_PAD, EV.PAD);
      }
    } else if (o.kind === 'orb') {
      if (!o.used && p.buffer > 0) {
        o.used = true;
        w.bonus += BIT;
        launch(w, V_JUMP, EV.ORB);
      }
    } else {
      w.dead = true;
      w.hit = o;
      w.ev |= EV.DIE;
      return;
    }
  }

  // карту пройдено до кінця
  if (w.dist >= w.finish) {
    w.won = true;
    w.ev |= EV.WIN;
    return;
  }
  // новий відрізок — нова контрольна точка: після падіння гра продовжиться з його початку, а не з самого старту
  while (w.mi + 1 < w.marks.length && w.dist >= w.marks[w.mi + 1].x) {
    const m = w.marks[++w.mi];
    w.check = { s: m.s, n: m.n, x: m.x, score: score(w), speed: startSpeed(m.n, w.touch), touch: w.touch };
    w.ev |= EV.SEASON;
  }
  // пройдені відрізки й перешкоди більше не потрібні (об'єкти перешкод — назад у запас); траса будується далі
  if (w.mi > 1) {
    w.marks.shift();
    w.mi--;
  }
  while (w.obs.length && w.obs[0].cx + CELL < w.dist - w.behind) w.pool.push(w.obs.shift());
  spawn(w);
}
