export const CELL = 8;
export const JUMP_H = 20, JUMP_L = 40;            // стрибок: 2,5 клітинки вгору й рівно 5 клітинок уперед
export const PAD_H = 26;                           // пружина підкидає вище
export const TOP = 27;                             // вище КІ-Рекс не злітає ніколи: що ближче до цієї висоти, то слабший поштовх угору
const G = 8 * JUMP_H / JUMP_L ** 2;                // «гравітація» на одиницю шляху (0,1)
const V_JUMP = 4 * JUMP_H / JUMP_L;                // нахил дуги на старті стрибка: 2 U вгору на 1 U уперед
const V_PAD = Math.sqrt(2 * G * PAD_H);
const V_SLAM = -2.4, V_MAX = -3.2;                 // «вниз» у повітрі — різке падіння; найбільша крутість падіння
export const PAD_L = JUMP_L * Math.sqrt(PAD_H / JUMP_H);   // довжина польоту з пружини (вища дуга — довша): майже 46 U
export const STAND = { w: 10, h: 15 }, DUCK = { w: 14, h: 9 };   // зони зіткнення: менші за спрайти (22×18 і 26×11)
/* де найкраще відштовхнутися (лівий край зони КІ-Рекса), щоб перестрибнути перешкоду: її середина опиняється під вершиною дуги */
export const takeoff = o => o.x + o.w / 2 - (JUMP_L + STAND.w) / 2;
const STEP_UP = 3;                                 // кут блока «прощає» стільки пікселів — КІ-Рекса підсаджує нагору
const COYOTE = .08, BUFFER = .14;                  // секунди: «час койота» і пам'ять про натискання, зроблене трохи зарано
export const BUG = { low: 2, high: 11 };           // дві «смуги» польоту жука, U над землею: низька — перестрибнути, висока — пригнутися
